export const CH_W = 5, CH_H = 7, ADVANCE = 6;

/** Pixel width of `str` rendered at integer scale `s` (no trailing gap). */
export function textW(str, s) {
  return str.length ? str.length * ADVANCE * s - s : 0;
}
export function textH(s) { return CH_H * s; }

// Build the glyph rectangles for a string as a single path. Horizontal runs are
// merged so a 19-character timestamp costs ~40 rects instead of ~200.
function glyphPath(ctx, str, x, y, s) {
  ctx.beginPath();
  const up = str.toUpperCase();
  for (let i = 0; i < up.length; i++) {
    const rows = G[up[i]];
    if (!rows) continue;
    const gx = x + i * ADVANCE * s;
    for (let r = 0; r < CH_H; r++) {
      const bits = rows[r];
      if (!bits) continue;
      let c = 0;
      while (c < CH_W) {
        if (bits & (0x10 >> c)) {
          let run = 1;
          while (c + run < CH_W && (bits & (0x10 >> (c + run)))) run++;
          ctx.rect(gx + c * s, y + r * s, run * s, s);
          c += run;
        } else c++;
      }
    }
  }
}

/**
 * Blit bitmap text. `shadow` is the dark keyline every DVR overlay carries so
 * the text survives over a blown-out white ceiling — which is where half of
 * these cameras point, so it is not optional.
 *
 * It is stroked, not offset. Stroking the glyph path outlines each rectangle
 * including the seams between adjacent ones, but the fill that follows uses the
 * same path and repaints every one of those interior pixels, so what is left is
 * a clean keyline around the outside of the glyph. An offset drop, which is what
 * this used to do, only protects two of the four sides.
 */
export function drawText(ctx, str, x, y, s, color, shadow = 'rgba(0,0,0,0.72)') {
  x = Math.round(x); y = Math.round(y);
  glyphPath(ctx, str, x, y, s);
  if (shadow) {
    ctx.strokeStyle = shadow;
    ctx.lineWidth = Math.max(1.2, s * 1.4);
    ctx.lineJoin = 'round';
    ctx.stroke();
  }
  ctx.fillStyle = color;
  ctx.fill();
}

/** Right-aligned variant: `rx` is the right edge. */
export function drawTextR(ctx, str, rx, y, s, color, shadow) {
  drawText(ctx, str, rx - textW(str, s), y, s, color, shadow);
}
